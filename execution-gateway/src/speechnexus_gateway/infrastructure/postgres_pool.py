"""Explicit bounded PostgreSQL pool for the gateway's coordination transactions.

The execution gateway is a separate deployment from the speech backend, so it repeats the
reviewed pool policy instead of importing the backend package: Read Committed, UTC, an
explicit ``search_path`` that keeps ``pg_temp`` behind the authoritative schema, a bounded
wait queue and no connection at import time. Production transactions use the gateway role,
which holds only the narrow DML grants generated by
``speechnexus_backend.speech.infrastructure.coordination_grants``.
"""

from __future__ import annotations

import re
from typing import Any

import psycopg
from psycopg import IsolationLevel
from psycopg.rows import dict_row
from psycopg_pool import ConnectionPool

type GatewayConnection = psycopg.Connection[dict[str, Any]]
type GatewayPool = ConnectionPool[GatewayConnection]

_SCHEMA_PATTERN = re.compile(r"[a-z][a-z0-9_]{2,62}")


def gateway_pool(
    database_url: str, *, schema: str = "speech", max_size: int = 4, max_waiting: int = 16
) -> GatewayPool:
    """Build a closed pool; the composition root decides when to open it."""
    if not _SCHEMA_PATTERN.fullmatch(schema):
        raise ValueError("Invalid control schema")
    if not 1 <= max_size <= 64 or not 1 <= max_waiting <= 1024:
        raise ValueError("Gateway pool must be bounded")

    def configure(connection: GatewayConnection) -> None:
        connection.isolation_level = IsolationLevel.READ_COMMITTED
        # PostgreSQL otherwise implicitly searches pg_temp before trusted schemas.
        connection.execute(
            "SELECT set_config('search_path', %s, false)", (schema + ",pg_catalog,pg_temp",)
        )
        connection.execute("SET TIME ZONE 'UTC'")
        connection.commit()

    return ConnectionPool[GatewayConnection](
        database_url,
        kwargs={"row_factory": dict_row, "connect_timeout": 3},
        configure=configure,
        name="gateway-coordination",
        min_size=0,
        max_size=max_size,
        max_waiting=max_waiting,
        timeout=3,
        open=False,
    )
